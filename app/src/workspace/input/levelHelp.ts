const names = (items: readonly LevelHelpItem[]) => items.map(([t]) => t).join("・");

/** 入力項目ごとの2文（標準で入れるもの・詳細で増えるもの） */
export function levelHelpLines(stage: StageId): readonly [string, string] {
  const d = LEVEL_HELP[stage];
  return [
    `標準では、${names(d.simple)}など、結果を大きく動かすものを入れます。`,
    d.fallback === "average"
      ? `詳細では、${names(d.detail)}を細かく設定できます。標準のままでも統計の平均で計算します。`
      : `詳細では、さらに${names(d.detail)}も入れられます。入れなければ${d.fallback === "estimate" ? "推定" : "既定の値"}で計算します。`,
  ];
}

/**
 * どの入力項目にも同じに出す文。入力項目ごとの2文（levelHelpLines）にまとめたので空。
 * 入力のパネルがこれと levelDiffLine を並べて出しているので、パネルを levelHelpLines に移すまで残す
 */
export const LEVEL_HELP_COMMON: readonly string[] = [];

/** 入力のパネルに出す文（levelHelpLines の2文をつなげたもの） */
export function levelDiffLine(stage: StageId): string {
  return levelHelpLines(stage).join("");
}
