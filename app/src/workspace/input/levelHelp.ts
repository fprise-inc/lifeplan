/** どのカードにも同じに出す文（標準と詳細の違い・出していない欄の扱い） */
export const LEVEL_HELP_COMMON: readonly string[] = [
  "標準は、結果を大きく動かす欄だけを出します。詳細では、すべての欄を出します。",
  "標準で出していない欄は、入れなくても推定や既定の値で計算します。詳細で入れた値は、標準に戻しても計算に効きます。切り替えは、この項目だけに効きます。",
];

/** カードごとの1行（「詳細で増える主な欄: 〇〇・〇〇 など。」） */
export function levelDiffLine(stage: StageId): string {
  const items = stage === "fee" ? [] : LEVEL_DIFF[stage];
  if (items.length === 0) return "詳細で増える欄: ありません（標準と詳細で同じ欄です）。";
  return `詳細で増える主な欄: ${items.map(([t]) => t).join("・")} など。`;
}
